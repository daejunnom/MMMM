//! Native owner-authorized creation in the one protected product store. A
//! declared target profile is a locator, never game evidence or a capability.
//! CAS bytes are flushed first; one SQLite transaction publishes all metadata.
//! A failed transaction may leave unreferenced CAS bytes eligible for normal GC.

use super::{
    BlobRef, DurableStore, StorageError, StorageResult,
    artifact::ResourceOwner,
    journal::{encode, pin_blob},
    project_resources::pin_resource_version,
};
use mmmm_contracts::{
    PrincipalId, ProjectId, ResourceId, Sha256Digest, canonical_bytes, parse_json,
    verify_projected_digest,
};
use rusqlite::{OptionalExtension, Transaction, TransactionBehavior, params};
use serde_json::{Value, json};

const MAX_DOCUMENT_BYTES: u64 = 8 * 1024 * 1024;
const MAX_METADATA_BYTES: usize = 16_384;
const MAX_PROJECTS: i64 = 4096;
const MAX_RESOURCE_ROWS: i64 = 65_536;
pub const POLICY_MEDIA_TYPE: &str = "application/vnd.mmmm.policy+json";
const INITIAL_POLICY: &[u8] = include_bytes!("../../../../examples/policy.json");

// Resource schemas match the existing immutable artifact and authored source
// registries. No second database, operation journal, grant or host is created.
pub(crate) const BOOTSTRAP_SCHEMA: &str = "
CREATE TABLE IF NOT EXISTS artifact_resources (
 resource_id TEXT PRIMARY KEY, resource_json TEXT NOT NULL, owner_json TEXT NOT NULL,
 blob_digest TEXT NOT NULL REFERENCES blobs(digest),
 byte_length INTEGER NOT NULL CHECK(byte_length>=0)
) STRICT;
CREATE TABLE IF NOT EXISTS project_resource_versions (
 project_id TEXT NOT NULL, resource_id TEXT NOT NULL,
 digest TEXT NOT NULL REFERENCES blobs(digest),
 resource_json TEXT NOT NULL CHECK(length(CAST(resource_json AS BLOB))<=16384),
 byte_length INTEGER NOT NULL CHECK(byte_length>=0),
 PRIMARY KEY(project_id,resource_id,digest)
) STRICT;
CREATE TABLE IF NOT EXISTS project_resource_heads (
 project_id TEXT NOT NULL, resource_id TEXT NOT NULL, digest TEXT NOT NULL,
 PRIMARY KEY(project_id,resource_id),
 FOREIGN KEY(project_id,resource_id,digest)
  REFERENCES project_resource_versions(project_id,resource_id,digest)
) STRICT;
CREATE TABLE IF NOT EXISTS project_resource_provenance (
 project_id TEXT NOT NULL, project_revision TEXT NOT NULL,
 resource_id TEXT NOT NULL, digest TEXT NOT NULL,
 project_definition TEXT NOT NULL DEFAULT 'Project' CHECK(project_definition='Project'),
 PRIMARY KEY(project_id,project_revision,resource_id,digest),
 FOREIGN KEY(project_id,resource_id,digest)
  REFERENCES project_resource_versions(project_id,resource_id,digest),
 FOREIGN KEY(project_definition,project_id,project_revision)
  REFERENCES documents(definition,document_id,content_hash)
) STRICT;
CREATE TABLE IF NOT EXISTS native_project_owners (
 project_id TEXT PRIMARY KEY REFERENCES project_heads(project_id),
 owner_principal TEXT NOT NULL,
 initial_revision TEXT NOT NULL CHECK(length(initial_revision)=64),
 policy_resource_id TEXT NOT NULL UNIQUE,
 policy_digest TEXT NOT NULL CHECK(length(policy_digest)=64),
 project_definition TEXT NOT NULL DEFAULT 'Project' CHECK(project_definition='Project'),
 policy_definition TEXT NOT NULL DEFAULT 'Policy' CHECK(policy_definition='Policy'),
 FOREIGN KEY(project_definition,project_id,initial_revision)
  REFERENCES documents(definition,document_id,content_hash),
 FOREIGN KEY(policy_definition,policy_resource_id,policy_digest)
  REFERENCES documents(definition,document_id,content_hash)
) STRICT;";

/// Constructed only in trusted native composition. IDs are newly generated by
/// the Coordinator; no caller JSON principal, policy reference or path is used.
pub struct ProjectBootstrapRequest<'a> {
    pub project: &'a Value,
    pub policy: &'a Value,
}

/// Implement with an opaque native-create permit captured from the currently
/// locked protected store and actual UID/SID-derived owner. It must check the
/// finite original deadline, cancellation, same store and current native owner.
/// authorize_create approves only these exact initial documents. Implementing
/// this trusted port from JSON labels is outside the supported boundary.
pub trait NativeOwnerCreatePermit {
    fn check(&self, store: &DurableStore) -> StorageResult<()>;
    fn authorize_create(
        &mut self,
        store: &DurableStore,
        request: &ProjectBootstrapRequest<'_>,
    ) -> StorageResult<PrincipalId>;
}

/// Internal creation result, with no RPC deserializer or authorization token.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct ProjectBootstrapReceipt {
    pub project_id: ProjectId,
    pub project_revision: Sha256Digest,
    pub project_blob: BlobRef,
    pub policy_resource: Value,
    /// A native owner identifier is a locator; it never grants Apply access.
    pub owner_principal: PrincipalId,
}

fn invalid(message: &'static str) -> StorageError {
    StorageError::InvalidInput(message.into())
}
fn contract(error: impl std::fmt::Display) -> StorageError {
    StorageError::Contract(error.to_string())
}

struct PreparedBootstrap {
    project: ProjectId,
    policy: ResourceId,
    revision: Sha256Digest,
    project_bytes: Vec<u8>,
    policy_bytes: Vec<u8>,
}

fn prepare(
    store: &DurableStore,
    request: &ProjectBootstrapRequest<'_>,
) -> StorageResult<PreparedBootstrap> {
    store
        .validator
        .validate("Project", request.project)
        .map_err(contract)?;
    store
        .validator
        .validate("Policy", request.policy)
        .map_err(contract)?;
    if parse_json(INITIAL_POLICY).map_err(contract)? != *request.policy {
        return Err(invalid(
            "Initial create requires the exact canonical default Policy",
        ));
    }
    let revision = verify_projected_digest("Project", request.project).map_err(contract)?;
    let project: ProjectId =
        serde_json::from_value(request.project["projectId"].clone()).map_err(contract)?;
    let policy: ResourceId =
        serde_json::from_value(request.project["policyResourceId"].clone()).map_err(contract)?;
    for field in ["prefabIds", "instanceIds", "ownedResources"] {
        if !request.project[field].as_array().is_some_and(Vec::is_empty) {
            return Err(invalid(
                "Fresh Project cannot reference absent authored documents",
            ));
        }
    }
    if request.project["resourceIds"] != json!([policy.as_str()]) {
        return Err(invalid(
            "Fresh Project must reference exactly its initial Policy resource",
        ));
    }
    let project_bytes = canonical_bytes(request.project).map_err(contract)?;
    let policy_bytes = canonical_bytes(request.policy).map_err(contract)?;
    if project_bytes.len() as u64 > MAX_DOCUMENT_BYTES
        || policy_bytes.len() as u64 > MAX_DOCUMENT_BYTES
    {
        return Err(invalid(
            "Initial Project/Policy exceeds its document budget",
        ));
    }
    Ok(PreparedBootstrap {
        project,
        policy,
        revision,
        project_bytes,
        policy_bytes,
    })
}

fn fresh_identity(
    transaction: &Transaction<'_>,
    project: &ProjectId,
    policy: &ResourceId,
) -> StorageResult<()> {
    let occupied: i64 = transaction.query_row(
        "SELECT EXISTS(SELECT 1 FROM project_heads WHERE project_id=?1) OR EXISTS(SELECT 1 FROM documents WHERE definition='Project' AND document_id=?1) OR EXISTS(SELECT 1 FROM operations WHERE project_id=?1) OR EXISTS(SELECT 1 FROM native_project_owners WHERE project_id=?1) OR EXISTS(SELECT 1 FROM project_resource_versions WHERE project_id=?1) OR EXISTS(SELECT 1 FROM artifact_resources WHERE resource_id=?2) OR EXISTS(SELECT 1 FROM documents WHERE definition='Policy' AND document_id=?2) OR EXISTS(SELECT 1 FROM project_resource_versions WHERE resource_id=?2)",
        params![project.as_str(), policy.as_str()], |row| row.get(0),
    )?;
    if occupied != 0 {
        return Err(StorageError::Conflict("Fresh Project/Policy identity"));
    }
    let projects: i64 =
        transaction.query_row("SELECT count(*) FROM project_heads", [], |row| row.get(0))?;
    let resources: i64 =
        transaction.query_row("SELECT count(*) FROM artifact_resources", [], |row| {
            row.get(0)
        })?;
    if projects >= MAX_PROJECTS || resources >= MAX_RESOURCE_ROWS {
        return Err(invalid(
            "Initial Project/Policy registry capacity exhausted",
        ));
    }
    Ok(())
}

/// Create only a fresh, empty Project and its exact canonical Policy. Existing
/// IDs always conflict, including after restart; no old document or ACL is
/// overwritten. This does not install a context, grant, provider or world task.
pub fn create_project(
    store: &mut DurableStore,
    permit: &mut dyn NativeOwnerCreatePermit,
    request: &ProjectBootstrapRequest<'_>,
) -> StorageResult<ProjectBootstrapReceipt> {
    permit.check(store)?;
    let owner = permit.authorize_create(store, request)?;
    permit.check(store)?;
    let PreparedBootstrap {
        project,
        policy,
        revision,
        project_bytes,
        policy_bytes,
    } = prepare(store, request)?;
    permit.check(store)?;
    let policy_blob = store.cas.put(&policy_bytes)?;
    let checked_policy = store.cas.read_verified_document::<StorageError, _>(
        &policy_blob,
        MAX_DOCUMENT_BYTES,
        || permit.check(store),
    )?;
    if checked_policy != policy_bytes
        || parse_json(&checked_policy).map_err(contract)? != *request.policy
    {
        return Err(StorageError::Corrupt(
            "Initial canonical Policy bytes differ".into(),
        ));
    }
    permit.check(store)?;
    let project_blob = store.cas.put(&project_bytes)?;
    let checked_project = store.cas.read_verified_document::<StorageError, _>(
        &project_blob,
        MAX_DOCUMENT_BYTES,
        || permit.check(store),
    )?;
    if checked_project != project_bytes
        || parse_json(&checked_project).map_err(contract)? != *request.project
    {
        return Err(StorageError::Corrupt(
            "Initial canonical Project bytes differ".into(),
        ));
    }
    let resource = json!({"resourceId":policy,"sha256":policy_blob.digest,
        "mediaType":POLICY_MEDIA_TYPE,"sizeBytes":policy_blob.byte_length});
    store
        .validator
        .validate("ResourceRef", &resource)
        .map_err(contract)?;
    let resource_json = encode(&resource)?;
    let owner_json = encode(&ResourceOwner::Project(project.clone()))?;
    if resource_json.len() > MAX_METADATA_BYTES || owner_json.len() > MAX_METADATA_BYTES {
        return Err(invalid("Initial resource metadata exceeds its budget"));
    }
    let transaction =
        Transaction::new_unchecked(&store.connection, TransactionBehavior::Immediate)?;
    transaction.execute_batch(BOOTSTRAP_SCHEMA)?;
    fresh_identity(&transaction, &project, &policy)?;
    pin_blob(&transaction, "project", project.as_str(), &project_blob)?;
    pin_blob(&transaction, "artifact", policy.as_str(), &policy_blob)?;
    pin_resource_version(&transaction, &project, &policy, &policy_blob)?;
    transaction.execute(
        "INSERT INTO documents(definition,document_id,content_hash,blob_digest) VALUES('Policy',?1,?2,?2)",
        params![policy.as_str(), policy_blob.digest.as_str()],
    )?;
    transaction.execute(
        "INSERT INTO documents(definition,document_id,content_hash,blob_digest) VALUES('Project',?1,?2,?3)",
        params![project.as_str(), revision.as_str(), project_blob.digest.as_str()],
    )?;
    transaction.execute(
        "INSERT INTO artifact_resources(resource_id,resource_json,owner_json,blob_digest,byte_length) VALUES(?1,?2,?3,?4,?5)",
        params![policy.as_str(), resource_json, owner_json, policy_blob.digest.as_str(), policy_blob.byte_length as i64],
    )?;
    transaction.execute(
        "INSERT INTO project_resource_versions(project_id,resource_id,digest,resource_json,byte_length) VALUES(?1,?2,?3,?4,?5)",
        params![project.as_str(), policy.as_str(), policy_blob.digest.as_str(), resource_json, policy_blob.byte_length as i64],
    )?;
    transaction.execute(
        "INSERT INTO project_resource_heads(project_id,resource_id,digest) VALUES(?1,?2,?3)",
        params![
            project.as_str(),
            policy.as_str(),
            policy_blob.digest.as_str()
        ],
    )?;
    transaction.execute(
        "INSERT INTO project_resource_provenance(project_id,project_revision,resource_id,digest) VALUES(?1,?2,?3,?4)",
        params![project.as_str(), revision.as_str(), policy.as_str(), policy_blob.digest.as_str()],
    )?;
    transaction.execute(
        "INSERT INTO project_heads(project_id,revision,blob_digest) VALUES(?1,?2,?3)",
        params![
            project.as_str(),
            revision.as_str(),
            project_blob.digest.as_str()
        ],
    )?;
    transaction.execute(
        "INSERT INTO native_project_owners(project_id,owner_principal,initial_revision,policy_resource_id,policy_digest) VALUES(?1,?2,?3,?4,?5)",
        params![project.as_str(), owner.as_str(), revision.as_str(), policy.as_str(), policy_blob.digest.as_str()],
    )?;
    permit.check(store)?;
    if permit.authorize_create(store, request)? != owner {
        return Err(StorageError::Conflict(
            "Native Project create owner changed",
        ));
    }
    permit.check(store)?;
    transaction.commit()?;
    Ok(ProjectBootstrapReceipt {
        project_id: project,
        project_revision: revision,
        project_blob,
        policy_resource: resource,
        owner_principal: owner,
    })
}

/// Trusted metadata lookup for reopened native composition. The caller must
/// compare this registration with an independently captured current native
/// owner and authorize every later source read. This opens no CAS and grants
/// no context, Project access, Apply, region or redistribution permission.
pub fn registered_native_project_owner(
    store: &DurableStore,
    project: &ProjectId,
) -> StorageResult<PrincipalId> {
    let table: i64 = store.connection.query_row(
        "SELECT EXISTS(SELECT 1 FROM sqlite_master WHERE type='table' AND name='native_project_owners')",
        [], |row| row.get(0),
    )?;
    if table != 1 {
        return Err(StorageError::NotFound("Native Project owner registration"));
    }
    let owner: Option<String> = store.connection.query_row(
        "SELECT substr(o.owner_principal,1,129) FROM native_project_owners o JOIN project_heads h ON h.project_id=o.project_id JOIN documents p ON p.definition=o.project_definition AND p.definition='Project' AND p.document_id=o.project_id AND p.content_hash=o.initial_revision JOIN documents d ON d.definition=o.policy_definition AND d.definition='Policy' AND d.document_id=o.policy_resource_id AND d.content_hash=o.policy_digest AND d.blob_digest=o.policy_digest WHERE o.project_id=?1",
        [project.as_str()], |row| row.get(0),
    ).optional()?;
    PrincipalId::new(owner.ok_or(StorageError::NotFound("Native Project owner registration"))?)
        .map_err(|_| StorageError::Corrupt("Native Project owner registration is invalid".into()))
}

